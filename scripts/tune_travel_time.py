"""
Búsqueda aleatoria de hiperparámetros del modelo de corrección de tiempo de
viaje, con validación anidada agrupada por centro de trabajo.

No modifica el modelo de producción: solo mide si ajustar los hiperparámetros
mejora el error frente a los valores fijos de `train_travel_time.py`.

1. Búsqueda aleatoria sobre todo el dataset (GroupKFold de 5 pliegues).
2. Validación anidada: en cada pliegue externo se busca solo con los datos de
   entrenamiento (GroupKFold interno) y se evalúa en los grupos no vistos. Así
   el error reportado no está inflado por haber elegido los parámetros sobre
   los mismos datos.

Uso:
    PYTHONPATH=. python scripts/tune_travel_time.py
"""

import os
import random
import sys
import time

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
import xgboost as xgb
from sklearn.model_selection import GroupKFold
from sklearn.metrics import mean_absolute_error

from ml_pipeline.train_travel_time import cargar, construir_X, DATA_PATH

OUT_PATH = "evaluation/model/hyperparameter_search.md"
N_TRIALS_FULL = 30      # combinaciones en la búsqueda sobre todo el dataset
N_TRIALS_NESTED = 15    # combinaciones por pliegue externo
OUTER_SPLITS = 5
INNER_SPLITS = 4
SEED = 42

FIXED = dict(n_estimators=400, learning_rate=0.05, max_depth=5, subsample=0.85,
             colsample_bytree=0.85, min_child_weight=3, reg_lambda=1.5)

SPACE = {
    "n_estimators": [200, 300, 400, 600, 800],
    "learning_rate": [0.02, 0.03, 0.05, 0.08, 0.1, 0.15],
    "max_depth": [3, 4, 5, 6, 7, 8],
    "subsample": [0.6, 0.7, 0.85, 1.0],
    "colsample_bytree": [0.6, 0.7, 0.85, 1.0],
    "min_child_weight": [1, 3, 5, 10],
    "reg_lambda": [0.5, 1.0, 1.5, 3.0, 5.0],
}


def sample_params(rng):
    return {k: rng.choice(v) for k, v in SPACE.items()}


def make_model(params):
    return xgb.XGBRegressor(objective="reg:squarederror", random_state=SEED, n_jobs=-1, **params)


def cv_mae(X, y_log, y_min, groups, params, splits):
    pred = np.zeros(len(y_min))
    for tr, te in GroupKFold(n_splits=splits).split(X, y_log, groups):
        m = make_model(params).fit(X.iloc[tr], y_log[tr])
        pred[te] = np.expm1(m.predict(X.iloc[te]))
    return mean_absolute_error(y_min, pred)


def random_search(X, y_log, y_min, groups, n_trials, splits, rng):
    trials = []
    seen = set()
    while len(trials) < n_trials:
        p = sample_params(rng)
        key = tuple(sorted(p.items()))
        if key in seen:
            continue
        seen.add(key)
        trials.append((cv_mae(X, y_log, y_min, groups, p, splits), p))
    trials.sort(key=lambda t: t[0])
    return trials


def main():
    t0 = time.time()
    df = cargar(DATA_PATH)
    X = construir_X(df)
    y_min = df.tt_min.values
    y_log = np.log1p(y_min)
    groups = df.workplace_id.values
    print(f"{len(df)} filas, {len(set(groups))} centros de trabajo")

    fixed_cv = cv_mae(X, y_log, y_min, groups, FIXED, OUTER_SPLITS)
    print(f"[1] Valores fijos, CV {OUTER_SPLITS} pliegues: MAE {fixed_cv:.3f} min  ({time.time()-t0:.0f} s)")

    rng = random.Random(SEED)
    full = random_search(X, y_log, y_min, groups, N_TRIALS_FULL, OUTER_SPLITS, rng)
    best_cv, best_params = full[0]
    print(f"[1] Mejor de {N_TRIALS_FULL} combinaciones: MAE {best_cv:.3f} min  {best_params}  ({time.time()-t0:.0f} s)")

    # Validación anidada
    outer_fixed, outer_tuned, chosen = np.zeros(len(y_min)), np.zeros(len(y_min)), []
    for k, (tr, te) in enumerate(GroupKFold(n_splits=OUTER_SPLITS).split(X, y_log, groups), 1):
        Xtr, ytr_log, ytr_min, gtr = X.iloc[tr], y_log[tr], y_min[tr], groups[tr]
        trials = random_search(Xtr, ytr_log, ytr_min, gtr, N_TRIALS_NESTED, INNER_SPLITS, random.Random(SEED + k))
        p = trials[0][1]
        chosen.append((trials[0][0], p))
        outer_tuned[te] = np.expm1(make_model(p).fit(Xtr, ytr_log).predict(X.iloc[te]))
        outer_fixed[te] = np.expm1(make_model(FIXED).fit(Xtr, ytr_log).predict(X.iloc[te]))
        print(f"[2] pliegue externo {k}/{OUTER_SPLITS}: fijo {mean_absolute_error(y_min[te], outer_fixed[te]):.3f} | "
              f"ajustado {mean_absolute_error(y_min[te], outer_tuned[te]):.3f}  ({time.time()-t0:.0f} s)")

    nested_fixed = mean_absolute_error(y_min, outer_fixed)
    nested_tuned = mean_absolute_error(y_min, outer_tuned)
    print(f"[2] Anidado — fijo: {nested_fixed:.3f} min | con búsqueda: {nested_tuned:.3f} min")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("# Hyperparameter search for the travel-time correction model\n\n")
        f.write("Generated by `scripts/tune_travel_time.py`. It does not change the deployed model.\n\n")
        f.write(f"Data: {len(df)} trips, {len(set(groups))} workplaces; "
                f"GroupKFold by `workplace_id`; metric: MAE in minutes; target `log1p(tt_min)`.\n\n")
        f.write("## Search space\n\n")
        for k, v in SPACE.items():
            f.write(f"- `{k}`: {v}\n")
        f.write(f"\n## 1. Random search on the whole dataset ({N_TRIALS_FULL} combinations, {OUTER_SPLITS} folds)\n\n")
        f.write(f"- Fixed (deployed) configuration: MAE {fixed_cv:.3f} min\n")
        f.write(f"- Best combination: MAE {best_cv:.3f} min — `{best_params}`\n")
        f.write(f"- Worst combination: MAE {full[-1][0]:.3f} min\n")
        f.write(f"- Median of the combinations: MAE {float(np.median([t[0] for t in full])):.3f} min\n\n")
        f.write("This comparison is optimistic for the best combination, which was chosen on the same folds on which it is measured.\n\n")
        f.write(f"## 2. Nested validation ({OUTER_SPLITS} outer folds, {N_TRIALS_NESTED} combinations and {INNER_SPLITS} inner folds)\n\n")
        f.write("| Procedure | MAE (min) |\n|---|---|\n")
        f.write(f"| Fixed (deployed) configuration | {nested_fixed:.3f} |\n")
        f.write(f"| Random search inside each outer fold | {nested_tuned:.3f} |\n\n")
        f.write("Combination chosen in each outer fold (inner MAE, parameters):\n\n")
        for i, (m, p) in enumerate(chosen, 1):
            f.write(f"{i}. {m:.3f} — `{p}`\n")
    print(f"\nGuardado: {OUT_PATH}  ({time.time()-t0:.0f} s)")


if __name__ == "__main__":
    main()
