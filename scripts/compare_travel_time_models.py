"""
Compara XGBoost con otros regresores para corregir el tiempo de OSRM, con la
misma validación cruzada (GroupKFold por centro de trabajo, 5 pliegues), el
mismo objetivo log(1 + t) y las mismas variables que train_travel_time.py.
Guarda las métricas globales, por pliegue y por modo.

Uso:
    python scripts/compare_travel_time_models.py
"""

import os
import sys

import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.ensemble import HistGradientBoostingRegressor, RandomForestRegressor
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import GroupKFold
from sklearn.neural_network import MLPRegressor
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ml_pipeline.train_travel_time import DATA_PATH, cargar, construir_X  # noqa: E402

OUT_PATH = "evaluation/model/travel_time_model_comparison.md"
SEED = 42

XGB_PARAMS = dict(objective="reg:squarederror", n_estimators=400, learning_rate=0.05,
                  max_depth=5, subsample=0.85, colsample_bytree=0.85,
                  min_child_weight=3, reg_lambda=1.5, random_state=SEED)

MODELOS = {
    "Linear regression": lambda: LinearRegression(),
    "Random forest": lambda: RandomForestRegressor(
        n_estimators=400, min_samples_leaf=2, n_jobs=-1, random_state=SEED),
    "Histogram gradient boosting": lambda: HistGradientBoostingRegressor(
        max_iter=400, learning_rate=0.05, max_leaf_nodes=31, random_state=SEED),
    "MLP (2 x 64)": lambda: make_pipeline(StandardScaler(), MLPRegressor(
        hidden_layer_sizes=(64, 64), early_stopping=True, max_iter=500, random_state=SEED)),
    "XGBoost": lambda: xgb.XGBRegressor(**XGB_PARAMS),
}


def metricas(y, p):
    return dict(
        MAE=mean_absolute_error(y, p),
        RMSE=float(np.sqrt(mean_squared_error(y, p))),
        MAPE=float(np.mean(np.abs((y - p) / np.clip(y, 1, None))) * 100),
        R2=r2_score(y, p),
    )


def main():
    df = cargar(DATA_PATH)
    X = construir_X(df)
    y = df.tt_min.values
    y_log = np.log1p(y)
    grupos = df.workplace_id.values
    pliegues = list(GroupKFold(n_splits=5).split(X, y_log, grupos))

    oof = {"OSRM (no correction)": df.osrm_min.values.astype(float)}
    por_pliegue = {"OSRM (no correction)": [metricas(y[te], oof["OSRM (no correction)"][te])["MAE"]
                                            for _, te in pliegues]}
    for nombre, crear in MODELOS.items():
        pred = np.zeros(len(y))
        maes = []
        for tr, te in pliegues:
            m = crear().fit(X.iloc[tr], y_log[tr])
            pred[te] = np.expm1(m.predict(X.iloc[te]))
            maes.append(metricas(y[te], pred[te])["MAE"])
        oof[nombre] = pred
        por_pliegue[nombre] = maes
        print(f"{nombre:<30} MAE {metricas(y, pred)['MAE']:.2f}  folds {np.round(maes, 2)}")

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("# Travel-time correction: model comparison\n\n")
        f.write(f"Generated by `scripts/compare_travel_time_models.py`; {len(y)} trips, "
                "five-fold GroupKFold by workplace, log(1 + t) target, same features for every model.\n\n")
        f.write("| Estimator | MAE (min) | RMSE (min) | MAPE (%) | R² | Fold MAE mean ± SD | Fold MAE min–max |\n")
        f.write("|---|---|---|---|---|---|---|\n")
        for nombre, pred in oof.items():
            m = metricas(y, pred)
            fm = np.array(por_pliegue[nombre])
            f.write(f"| {nombre} | {m['MAE']:.2f} | {m['RMSE']:.2f} | {m['MAPE']:.1f} | {m['R2']:.3f} | "
                    f"{fm.mean():.2f} ± {fm.std(ddof=1):.2f} | {fm.min():.2f}–{fm.max():.2f} |\n")
        f.write("\n## MAE by mode (min)\n\n| Estimator | " + " | ".join(sorted(df.modo.unique())) + " |\n")
        f.write("|---|" + "---|" * df.modo.nunique() + "\n")
        for nombre, pred in oof.items():
            celdas = []
            for modo in sorted(df.modo.unique()):
                mask = (df.modo == modo).values
                celdas.append(f"{metricas(y[mask], pred[mask])['MAE']:.2f}")
            f.write(f"| {nombre} | " + " | ".join(celdas) + " |\n")
    print(f"Guardado: {OUT_PATH}")


if __name__ == "__main__":
    main()
