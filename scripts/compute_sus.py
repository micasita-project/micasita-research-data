"""
Resultados de la evaluación de usabilidad (SUS, tareas y aceptación del Top-1)
a partir de las respuestas anonimizadas.

Uso:
    python scripts/compute_sus.py
"""

import csv
from collections import Counter

import numpy as np
from scipy import stats

DATA_PATH = "evaluation/usability/sus_responses_anonymised.csv"
OUT_PATH = "evaluation/usability/sus_results.md"
SEED = 42
N_BOOT = 10_000
BENCHMARK = 68
# Cortes de las bandas, cercanos a las medias adjetivas de Bangor et al. (2009).
CORTE_BUENO, CORTE_EXCELENTE = 71, 85


def sus(q):
    impares = q[:, 0::2] - 1
    pares = 5 - q[:, 1::2]
    return np.hstack([impares, pares]), (impares.sum(1) + pares.sum(1)) * 2.5


def alfa_cronbach(items):
    k = items.shape[1]
    return k / (k - 1) * (1 - items.var(0, ddof=1).sum() / items.sum(1).var(ddof=1))


def main():
    filas = list(csv.DictReader(open(DATA_PATH, encoding="utf-8")))
    q = np.array([[int(f[f"q{i}"]) for i in range(1, 11)] for f in filas])
    contrib, s = sus(q)
    assert np.allclose(s, [float(f["sus_score"]) for f in filas]), "sus_score no coincide con los ítems"

    rng = np.random.default_rng(SEED)
    boot = [rng.choice(s, len(s)).mean() for _ in range(N_BOOT)]
    ic = np.percentile(boot, [2.5, 97.5])
    w = stats.wilcoxon(s - BENCHMARK, alternative="greater")
    modos = sorted({f["transport_mode"] for f in filas})
    grupos = [s[[f["transport_mode"] == m for f in filas]] for m in modos]
    kw = stats.kruskal(*grupos)
    n = len(s)

    lineas = ["# Usability evaluation (SUS)\n",
              f"Generated by `scripts/compute_sus.py` from `{DATA_PATH}` (N = {n}).\n",
              "## SUS score\n",
              f"- Mean {s.mean():.1f} (SD {s.std(ddof=1):.1f}); 95% bootstrap CI {ic[0]:.2f}–{ic[1]:.2f} "
              f"({N_BOOT:,} resamples, seed {SEED}).",
              f"- Median {np.median(s):.1f}; range {s.min():.1f}–{s.max():.1f}.",
              f"- Bands: below {CORTE_BUENO} {int((s < CORTE_BUENO).sum())}; Good ({CORTE_BUENO}–<{CORTE_EXCELENTE}) "
              f"{int(((s >= CORTE_BUENO) & (s < CORTE_EXCELENTE)).sum())}; Excellent (≥ {CORTE_EXCELENTE}) "
              f"{int((s >= CORTE_EXCELENTE).sum())}.",
              f"- Scores above {BENCHMARK}: {int((s > BENCHMARK).sum())} of {n}; one-sided one-sample Wilcoxon "
              f"V = {w.statistic:.0f}, p = {w.pvalue:.1e}.",
              f"- Cronbach's α = {alfa_cronbach(contrib):.2f}.",
              f"- Item means (1–5): positive items {q[:, 0::2].mean(0).min():.2f}–{q[:, 0::2].mean(0).max():.2f}, "
              f"negative items {q[:, 1::2].mean(0).min():.2f}–{q[:, 1::2].mean(0).max():.2f}.\n",
              "## By transport mode\n", "| Mode | n | Mean SUS | SD |", "|---|---|---|---|"]
    for m, g in zip(modos, grupos):
        lineas.append(f"| {m} | {len(g)} | {g.mean():.1f} | {g.std(ddof=1):.1f} |")
    lineas += ["", f"Kruskal–Wallis H = {kw.statistic:.2f}, p = {kw.pvalue:.3f}, "
                   f"ε² = {kw.statistic / (n - 1):.2f}.\n",
               "## Tasks\n", "| Task | Completed | Mean time of completed tasks (min) |", "|---|---|---|"]
    for t in (1, 2, 3):
        hecho = np.array([f[f"t{t}_completed"] == "1" for f in filas])
        tiempo = np.array([float(f[f"t{t}_time_min"] or "nan") for f in filas])
        lineas.append(f"| T{t} | {hecho.sum()} of {n} ({hecho.mean():.0%}) | {tiempo[hecho].mean():.2f} |")
    top1 = Counter(f["top1_accept"] for f in filas)
    usa = Counter(f["uses_housing_apps"] for f in filas)
    lineas += ["", "## Other answers\n",
               f"- Top-1 acceptance: yes {top1['yes']}, maybe {top1['maybe']}, no {top1['no']}.",
               f"- Current use of housing-search applications: yes {usa['yes']}, sometimes {usa['sometimes']}, "
               f"no {usa['no']}."]

    open(OUT_PATH, "w", encoding="utf-8").write("\n".join(lineas) + "\n")
    print("\n".join(lineas))
    print(f"\nGuardado: {OUT_PATH}")


if __name__ == "__main__":
    main()
