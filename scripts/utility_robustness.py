"""
Solidez de la utilidad multicriterio frente a los rankings humanos (NDCG@5):
  1. Aporte de cada término (ablación acumulativa).
  2. Sensibilidad a los pesos (cada peso por separado y los cuatro al azar).
  3. Pesos aprendidos de los rankings humanos con regresión logística por pares,
     validada dejando fuera un escenario cada vez.
  4. Orden por costo generalizado con el valor social del tiempo del MEF.

Los términos de presupuesto y área se recalculan con sus fórmulas; el de
distancia se recupera del puntaje registrado, porque la hoja no guarda la
distancia de ruta.

Uso:
    python scripts/utility_robustness.py
"""

import csv
import itertools
import os
import sys

import numpy as np
from scipy.stats import wilcoxon
from sklearn.linear_model import LogisticRegression

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
import ablation_ndcg5 as A  # noqa: E402

OUT_PATH = "evaluation/ranking/utility_robustness.md"
SEED = 42
N_RANDOM = 500
VALOR_TIEMPO_MEF = 6.81   # soles por hora, propósito laboral urbano (MEF, Anexo 11)
VIAJES_MES = 44           # ida y vuelta, 22 días laborables


def f_budget(r):
    return (1 - r) * 20 if r <= 1 else -min(35, (r - 1) * 60)


def f_area(a):
    return 5 if a >= 40 else 3 if a >= 25 else 1 if a >= 15 else (-2 if 0 < a < 15 else 0)


def cargar():
    esc = A.cargar()
    filas = {(int(r["Escenario"]), r["Vivienda ID"]): r for r in csv.DictReader(open(A.SCORES_PATH, encoding="utf-8"))}
    for k, items in esc.items():
        for it in items:
            r = filas[(k, it["viv"])]
            it["budget"] = float(r["Presupuesto S/"])
            it["area"] = float(r["Area m2"])
            it["ft"] = A.f_tt(it["t_xgb"])
            it["fb"] = f_budget(it["precio"] / it["budget"])
            it["fa"] = f_area(it["area"])
            resto = it["score"] - 40 - it["ft"] - it["fb"] - it["fa"]
            it["fd"] = min([3, 1, 0, -3], key=lambda v: abs(v - resto))
    return esc


def ndcg_media(esc, clave):
    return np.array([A.ndcg5(items, clave) for items in esc.values()])


def utilidad(w):
    return lambda it: (-(w[0] * it["ft"] + w[1] * it["fb"] + w[2] * it["fa"] + w[3] * it["fd"]), it["modelo"])


def pares(esc, X, claves):
    P, Y = [], []
    for k in claves:
        for i, j in itertools.combinations(range(10), 2):
            d = X[k][i] - X[k][j]
            y = int(esc[k][i]["humano"] < esc[k][j]["humano"])
            P += [d, -d]
            Y += [y, 1 - y]
    return np.array(P), np.array(Y)


def main():
    esc = cargar()
    lineas = ["# Robustness of the multi-criteria utility\n",
              f"Generated by `scripts/utility_robustness.py` ({len(esc)} scenarios x 10 candidates). "
              "Reference values are recomputed from times stored in whole minutes, so the full utility scores "
              "slightly below the recorded ranking.\n"]

    completa = ndcg_media(esc, utilidad([1, 1, 1, 1]))
    variantes = [("Corrected time only (price tiebreak)", lambda it: (round(it["t_xgb"]), it["precio"])),
                 ("Time + budget", utilidad([1, 1, 0, 0])),
                 ("Time + budget + area", utilidad([1, 1, 1, 0])),
                 ("Time + budget + distance", utilidad([1, 1, 0, 1])),
                 ("Full utility (recomputed)", utilidad([1, 1, 1, 1])),
                 ("Full utility (recorded ranking)", lambda it: it["modelo"])]
    lineas += ["## 1. Contribution of each term\n", "| Ordering | Mean NDCG@5 | vs. recorded ranking: better / equal / worse | p |",
               "|---|---|---|---|"]
    registrado = ndcg_media(esc, lambda it: it["modelo"])
    for nombre, clave in variantes:
        v = ndcg_media(esc, clave)
        d = registrado - v
        nz = d[np.abs(d) > 1e-9]
        p = f"{wilcoxon(nz).pvalue:.3f}" if len(nz) else "—"
        lineas.append(f"| {nombre} | {v.mean():.3f} | {(d > 1e-9).sum()} / {(np.abs(d) <= 1e-9).sum()} / {(d < -1e-9).sum()} | {p} |")

    lineas += ["", "## 2. Sensitivity to the weights\n", f"Reference (recomputed full utility): {completa.mean():.3f}.\n",
               "| Term | ×0 | ×0.5 | ×0.75 | ×1.25 | ×1.5 | ×2 |", "|---|---|---|---|---|---|---|"]
    for i, nombre in enumerate(["Time", "Budget", "Area", "Distance"]):
        celdas = [f"{ndcg_media(esc, utilidad([m if j == i else 1 for j in range(4)])).mean():.3f}"
                  for m in (0, 0.5, 0.75, 1.25, 1.5, 2)]
        lineas.append(f"| {nombre} | " + " | ".join(celdas) + " |")
    rng = np.random.default_rng(SEED)
    lineas += ["", "| All four weights perturbed at random | Mean | 5th–95th percentile | Minimum |", "|---|---|---|---|"]
    for amplitud in (0.25, 0.5):
        v = [ndcg_media(esc, utilidad(rng.uniform(1 - amplitud, 1 + amplitud, 4))).mean() for _ in range(N_RANDOM)]
        lineas.append(f"| ±{int(amplitud * 100)}% ({N_RANDOM} draws) | {np.mean(v):.3f} | "
                      f"{np.percentile(v, 5):.3f}–{np.percentile(v, 95):.3f} | {np.min(v):.3f} |")

    # Pesos aprendidos con las preferencias humanas, sin ver el escenario evaluado.
    X = {k: np.array([[it["t_xgb"], it["precio"] / it["budget"], np.log(max(it["area"], 1))] for it in items])
         for k, items in esc.items()}
    claves = list(esc)
    loso = []
    for k in claves:
        P, Y = pares(esc, X, [q for q in claves if q != k])
        escala = np.abs(P).mean(axis=0)
        w = LogisticRegression(fit_intercept=False).fit(P / escala, Y).coef_[0] / escala
        s = X[k] @ w
        loso.append(A.ndcg5([dict(it, _s=s[i]) for i, it in enumerate(esc[k])], lambda it: (-it["_s"], it["modelo"])))
    loso = np.array(loso)
    d = registrado - loso
    P, Y = pares(esc, X, claves)
    escala = np.abs(P).mean(axis=0)
    w = LogisticRegression(fit_intercept=False).fit(P / escala, Y).coef_[0] / escala
    lineas += ["", "## 3. Weights learned from the human rankings\n",
               "Pairwise logistic regression on corrected time (min), price-to-budget ratio and log floor area; "
               "leave-one-scenario-out evaluation.\n",
               f"- Leave-one-scenario-out NDCG@5: {loso.mean():.3f} (SD {loso.std(ddof=1):.3f}).",
               f"- Recorded ranking vs. learned weights: better / equal / worse {(d > 1e-9).sum()} / "
               f"{(np.abs(d) <= 1e-9).sum()} / {(d < -1e-9).sum()}, p = {wilcoxon(d[np.abs(d) > 1e-9]).pvalue:.3f}.",
               f"- Weights fitted on all scenarios: time {w[0]:.4f} per min, price-to-budget ratio {w[1]:.3f}, "
               f"log area {w[2]:.3f}; one minute of commute is worth {w[0] / w[1] * 100:.1f}% of the budget."]

    lineas += ["", "## 4. Generalised cost with the official value of time\n",
               f"Ordering by rent + value of time x {VIAJES_MES} trips x corrected time.\n",
               "| Value of time (PEN/h) | Mean NDCG@5 |", "|---|---|"]
    for vot in (VALOR_TIEMPO_MEF, 15, 40):
        v = ndcg_media(esc, lambda it, v=vot: (it["precio"] + v * VIAJES_MES * it["t_xgb"] / 60, it["modelo"]))
        lineas.append(f"| {vot} | {v.mean():.3f} |")

    open(OUT_PATH, "w", encoding="utf-8").write("\n".join(lineas) + "\n")
    print("\n".join(lineas))
    print(f"\nGuardado: {OUT_PATH}")


if __name__ == "__main__":
    main()
